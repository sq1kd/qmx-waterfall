/*
 * Draw spectrum line plot into the top SPEC_H rows of the canvas.
 * mag points to either the full fftshift'd array or the positive-only
 * sub-array; mag_len is the number of usable bins.
 */
static void draw_spectrum_strip(uint16_t *canvas_buf,
                                const float *mag, int mag_len)
{
    /* Clear spectrum rows to near-black background */
    for (int i = 0; i < SPEC_H * DISP_W; i++)
        canvas_buf[i] = SPEC_BG;

    const float dyn_db = s.wf_db_ceil - s.wf_db_floor;
    const float bot_db = s.wf_db_floor;

    int prev_y = -1;
    for (int px = 0; px < DISP_W; px++)
    {
        /* Linear interpolation: map pixel to fractional bin index */
        float fbin = (float)px * (float)(mag_len - 1) / (float)(DISP_W - 1);
        int bin = (int)fbin;
        if (bin >= mag_len - 1) bin = mag_len - 2;
        if (bin < 0) bin = 0;
        float frac = fbin - (float)bin;

        float m = mag[bin] * (1.0f - frac) + mag[bin + 1] * frac;
        float db = 10.0f * log10f(m + 1e-12f) + s.level_offset_db;
        float norm = (db - bot_db) / dyn_db;
        if (norm < 0.0f)
            norm = 0.0f;
        if (norm > 1.0f)
            norm = 1.0f;

        /* y=0 is top; high signal = low y_top (tall bar) */
        int y_top = (SPEC_H - 1) - (int)(norm * (SPEC_H - 1));

        if (prev_y != -1) {
            int y0 = prev_y;
            int y1 = y_top;
            if (y0 > y1) {
                int tmp = y0; y0 = y1; y1 = tmp;
            }
            for (int y = y0; y <= y1; y++) {
                canvas_buf[y * DISP_W + px] = SPEC_FG;
            }
        } else {
            canvas_buf[y_top * DISP_W + px] = SPEC_FG;
        }
        prev_y = y_top;
    }
}

/*
 * Draw the waterfall into rows WF_Y0 .. WF_Y0+WF_H-1 of the canvas.
 * Reads from the ring buffer of dB values, newest row at top.
 */
static void draw_waterfall(uint16_t *canvas_buf)
{
    if (!s.wf_db) return;

    for (int row = 0; row < WF_H; row++)
    {
        /* row 0 = newest (wf_write_idx - 1), row WF_H-1 = oldest */
        int ring_idx = (int)s.wf_write_idx - 1 - row;
        if (ring_idx < 0) ring_idx += WF_H;

        const float *db_row = &s.wf_db[ring_idx * DISP_W];
        uint16_t *px_row = &canvas_buf[(WF_Y0 + row) * DISP_W];

        for (int x = 0; x < DISP_W; x++)
        {
            px_row[x] = turbo_lut[db_to_color_idx(db_row[x])];
        }
    }
}

static void draw_filter_overlay(uint16_t *canvas_buf)
{
    if (s.filter_hz == 0 || s.sample_freq == 0) return;

    float center_bin = 0.0f;
    if (!marker_to_bin(&center_bin)) return;

    int nbins = effective_bins();
    float bw_bins = (float)s.filter_hz * (float)nbins / (float)s.sample_freq;
    if (s.view_mode == 0) {
        /* Full spectrum: bw_bins is relative to fft_size bins mapped to DISP_W */
        bw_bins = (float)s.filter_hz * (float)s.cfg.fft_size / (float)s.sample_freq;
    }

    float left_bin = center_bin - bw_bins * 0.5f;
    float right_bin = center_bin + bw_bins * 0.5f;

    switch (s.mode_code) {
        case 1: /* LSB */ left_bin = center_bin - bw_bins; right_bin = center_bin; break;
        case 2: /* USB */ left_bin = center_bin; right_bin = center_bin + bw_bins; break;
        default: break;
    }

    int left_px = bin_to_px(left_bin);
    int right_px = bin_to_px(right_bin);
    if (right_px < left_px) {
        int t = left_px; left_px = right_px; right_px = t;
    }

    /* Draw overlay on spectrum strip only (top SPEC_H rows) */
    for (int y = 0; y < SPEC_H; y++) {
        uint16_t *row = &canvas_buf[y * DISP_W];
        for (int x = left_px; x <= right_px; x++) {
            uint16_t cur = row[x];
            row[x] = ((cur >> 1) & 0x7BEF) + ((SPEC_FILTER_FILL >> 1) & 0x7BEF);
        }
        if (left_px >= 0 && left_px < DISP_W) row[left_px] = SPEC_FILTER_EDGE;
        if (right_px >= 0 && right_px < DISP_W) row[right_px] = SPEC_FILTER_EDGE;
    }
}

/*
 * Store a row of dB values into the waterfall ring buffer.
 * mag points to the (possibly positive-only) magnitude array; mag_len bins.
 * Each pixel is mapped from bins via linear interpolation, converted to dB.
 */
static void store_wf_row(const float *mag, int mag_len)
{
    if (!s.wf_db) return;

    float *dst = &s.wf_db[s.wf_write_idx * DISP_W];

    for (int px = 0; px < DISP_W; px++)
    {
        float fbin = (float)px * (float)(mag_len - 1) / (float)(DISP_W - 1);
        int bin = (int)fbin;
        if (bin >= mag_len - 1) bin = mag_len - 2;
        if (bin < 0) bin = 0;
        float frac = fbin - (float)bin;

        float m = mag[bin] * (1.0f - frac) + mag[bin + 1] * frac;
        dst[px] = 10.0f * log10f(m + 1e-12f) + s.level_offset_db;
    }

    s.wf_write_idx = (s.wf_write_idx + 1) % WF_H;
}


/* -------------------------------------------------------------------------- */
/* spectrum task (core 1)                                                     */
/* -------------------------------------------------------------------------- */

static void spectrum_task(void *arg)
{
    ESP_LOGI(TAG, "spectrum task started (fft=%u, %.1f lines/s, view=%u)",
             s.cfg.fft_size, s.cfg.lines_per_sec, s.view_mode);

    const uint32_t fft_size = s.cfg.fft_size;
    const uint32_t ms_per_line = (uint32_t)(1000.0f / s.cfg.lines_per_sec);
    TickType_t last_push = 0;
    while (true)
    {
        /* Wait for RX_DONE notification from core 0.
         * pdTRUE clears the notification count, but we drain the ring
         * buffer fully below so stacked notifications are harmless. */
        ulTaskNotifyTake(pdTRUE, portMAX_DELAY);

        if (s.uac_handle == NULL)
        {
            continue;
        }

        /* ---- Drain the UAC ring buffer completely ----
         * The USB host pushes data at 48 kHz × 6 B/frame = 288 KB/s.
         * We must consume it all to prevent ring buffer overflow and
         * the resulting byte-stream discontinuities.  Display rendering
         * is rate-limited separately below. */
        const uint8_t bytes_per_sample = s.bytes_per_sample;
        const uint8_t frame_bytes = bytes_per_sample * s.channels;

        while (true)
        {
            uint32_t bytes_read = 0;
            esp_err_t err = uac_host_device_read(s.uac_handle,
                                                 s.read_raw,
                                                 sizeof(s.read_raw),
                                                 &bytes_read,
                                                 0 /* non-blocking */);
            if (err != ESP_OK || bytes_read == 0)
            {
                break; /* ring buffer drained */
            }

            const uint32_t frames = bytes_read / frame_bytes;

            for (uint32_t f = 0; f < frames; f++)
            {
                const uint8_t *p = s.read_raw + f * frame_bytes;

                float i_samp, q_samp;

                if (s.bit_resolution == 24)
                {
                    bool use_24in4 = (bytes_per_sample >= 4);
                    if (use_24in4)
                    {
                        if (bytes_per_sample < 4 || frame_bytes < 8)
                        {
                            continue;
                        }
                        /* 24-bit audio in 4-byte container (right-justified / LSB-aligned):
                         * bytes [0]=LSB [1]=MID [2]=MSB [3]=pad(0).
                         * Read lower 3 bytes and sign-extend from bit 23. */
                        int32_t iv = (int32_t)(p[0] | ((uint32_t)p[1] << 8) | ((uint32_t)p[2] << 16));
                        if (iv & 0x800000) iv |= (int32_t)0xFF000000;
                        i_samp = (float)iv / 8388608.0f;

                        const uint8_t *q = p + bytes_per_sample;
                        int32_t qv = (int32_t)(q[0] | ((uint32_t)q[1] << 8) | ((uint32_t)q[2] << 16));
                        if (qv & 0x800000) qv |= (int32_t)0xFF000000;
                        q_samp = (float)qv / 8388608.0f;
                    }
                    else
                    {
                        int32_t iv = (int32_t)(p[0] | ((uint32_t)p[1] << 8) | ((uint32_t)p[2] << 16));
                        if (iv & 0x800000)
                            iv |= (int32_t)0xFF000000;
                        i_samp = (float)iv / 8388608.0f;

                        const uint8_t *q = p + bytes_per_sample;
                        int32_t qv = (int32_t)(q[0] | ((uint32_t)q[1] << 8) | ((uint32_t)q[2] << 16));
                        if (qv & 0x800000)
                            qv |= (int32_t)0xFF000000;
                        q_samp = (float)qv / 8388608.0f;
                    }
                }
                else
                {
                    /* 16-bit signed little-endian fallback */
                    int16_t iv = (int16_t)(p[0] | ((uint16_t)p[1] << 8));
                    i_samp = (float)iv / 32768.0f;
                    const uint8_t *q = p + bytes_per_sample;
                    int16_t qv = (int16_t)(q[0] | ((uint16_t)q[1] << 8));
                    q_samp = (float)qv / 32768.0f;
                }

                /* fft_buf layout: [Re0, Im0, Re1, Im1, ...] */
                uint32_t idx = s.accum_idx;
                s.fft_buf[idx * 2] = i_samp * s.window[idx];
                s.fft_buf[idx * 2 + 1] = q_samp * s.window[idx];
                s.accum_idx++;

                if (s.accum_idx >= fft_size)
                {
                    s.accum_idx = 0;

                    /* Run FFT — use ANSI C path to bypass AES3 SIMD */
                    dsps_fft2r_fc32_ansi(s.fft_buf, (int)fft_size);
                    dsps_bit_rev_fc32(s.fft_buf, (int)fft_size);

                    /* Compute magnitude² for each bin (unnormalized, matching Python
                     * convention: 10*log10(|X|²) so dB values are directly comparable
                     * with the pc/iq_live_view.py reference viewer). */
                    float mag[fft_size]; /* stack-allocated; fft_size ≤ 1024 */
                    for (uint32_t k = 0; k < fft_size; k++)
                    {
                        float re = s.fft_buf[k * 2];
                        float im = s.fft_buf[k * 2 + 1];
                        float pwr = re * re + im * im;
                        mag[k] = pwr;  /* store power; converted to dB later */
                    }

                    /* Shift so DC is in the centre (negative freq left) */
                    fftshift_mag(mag, (int)fft_size);

                    /* Select sub-array for positive-only mode */
                    const float *render_mag = mag;
                    int render_bins = (int)fft_size;
                    if (s.view_mode == 1)
                    {
                        render_mag = &mag[fft_size / 2];
                        render_bins = (int)(fft_size / 2);
                    }

                    /* Always store waterfall row (cheap, keeps history current) */
                    store_wf_row(render_mag, render_bins);

                    /* Rate-limited display push: render + push only when
                     * enough time has elapsed since the last frame. */
                    TickType_t now = xTaskGetTickCount();
                    TickType_t elapsed_ms = (now - last_push) * portTICK_PERIOD_MS;
                    if (last_push == 0 || elapsed_ms >= ms_per_line)
                    {
                        last_push = now;

                        /* Spectrum strip (top SPEC_H rows) */
                        draw_spectrum_strip(s.canvas_buf, render_mag, render_bins);

                        /* Waterfall (bottom WF_H rows) — redrawn from ring buffer */
                        draw_waterfall(s.canvas_buf);

                        draw_filter_overlay(s.canvas_buf);

                        /* IF marker: red vertical line through spectrum strip */
                        if (s.marker_px >= 0)
                            for (int y = 0; y < SPEC_H; y++)
                                s.canvas_buf[y * DISP_W + s.marker_px] = rgb565(0xFF, 0x00, 0x00);

                        if (lvgl_port_lock(0))
                        {
                            lv_obj_invalidate(s.canvas);
                            lvgl_port_unlock();
                        }
                    }

                } /* end FFT frame complete */
            } /* end per-frame loop */
        } /* end ring buffer drain loop */
    } /* end main task loop */
}

