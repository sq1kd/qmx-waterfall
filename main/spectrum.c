/*
 * Bin/pixel mapping.  In full-spectrum mode the full fft_size bins span
 * DISP_W pixels.  In positive-only mode only the upper half of the
 * fftshift output (bins fft_size/2 .. fft_size-1) is used, so the
 * effective bin count is fft_size/2.
 */
static int effective_bins(void)
{
    return s.view_mode == 1 ? (int)(s.cfg.fft_size / 2) : (int)s.cfg.fft_size;
}

static bool marker_to_bin(float *bin_out)
{
    if (s.marker_px < 0)
    {
        return false;
    }
    *bin_out = ((float)s.marker_px * (float)(effective_bins() - 1)) / (float)(DISP_W - 1);
    return true;
}

static int bin_to_px(float bin)
{
    int nbins = effective_bins();
    int px = (int)(bin * (float)(DISP_W - 1) / (float)(nbins - 1) + 0.5f);
    if (px < 0)
        px = 0;
    if (px >= DISP_W)
        px = DISP_W - 1;
    return px;
}

static void fftshift_mag(float *mag, int len)
{
    int half = len / 2;
    for (int i = 0; i < half; i++)
    {
        float t = mag[i];
        mag[i] = mag[i + half];
        mag[i + half] = t;
    }
}

#ifndef M_PI
#define M_PI 3.14159265358979323846f
#endif

static void build_hann_window(float *win, int len)
{
    for (int i = 0; i < len; i++)
    {
        win[i] = 0.5f * (1.0f - cosf(2.0f * (float)M_PI * (float)i / (float)(len - 1)));
    }
}

