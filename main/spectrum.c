/* Pack R5G6B5 for the ST7789 */
static inline uint16_t rgb565(uint8_t r, uint8_t g, uint8_t b)
{
    return ((uint16_t)(r & 0xF8) << 8) |
           ((uint16_t)(g & 0xFC) << 3) |
           ((uint16_t)(b >> 3));
}

#define SPEC_BG rgb565(0x00, 0x00, 0x08) /* near-black navy background */
#define SPEC_FG rgb565(0x00, 0xFF, 0x00) /* pure green trace           */
#define SPEC_FILTER_FILL rgb565(0x52, 0x52, 0x52)
#define SPEC_FILTER_EDGE rgb565(0x9A, 0x9A, 0x9A)

/* Map a dB value to a turbo LUT index (0..255), clamped. */
static inline uint8_t db_to_color_idx(float db)
{
    float range = s.wf_db_ceil - s.wf_db_floor;
    if (range < 1.0f) range = 1.0f;
    float norm = (db - s.wf_db_floor) / range;
    if (norm < 0.0f) norm = 0.0f;
    if (norm > 1.0f) norm = 1.0f;
    return (uint8_t)(norm * 255.0f + 0.5f);
}

